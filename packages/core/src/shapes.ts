import type { JsonObject } from "@dg/contract/records.ts";

/**
 * The process shapes, as the plugins run them. Each rule here has a twin of
 * the same name in `ontology/dg_process.shacl.ttl`, and `ontology/tests/cases.json`
 * holds one wrong graph per rule that both must catch. This side reads the
 * JSON-LD view that `toProcessJsonLd` writes, so a rule sees exactly what a
 * SHACL engine would see.
 */

export type Severity = "Violation" | "Warning" | "Info";

/** A pin has no id of its own, so its problems are reported under `_:`. */
export type ShapeProblem = { focus: string; rule: string; severity: Severity; message: string };

type Rule = { severity: Severity; message: string };

