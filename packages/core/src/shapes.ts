export type ShapeRule = keyof typeof SHAPE_RULES;

const UNITS = new Set(["Question", "Claim", "Evidence", "Source", "Protocol", "Study", "Run", "Code", "Output"]);
const CID = /^b[a-z2-7]{58}$/;
const DATE_TIME = /^-?\d{4,}-\d\d-\d\dT\d\d:\d\d:\d\d(\.\d+)?(Z|[+-]\d\d:\d\d)?$/;
const AGENT = /^(did:[a-z0-9]+:|https:\/\/orcid\.org\/)/;
const STATUSES = ["planned", "running", "completed", "failed"];
const DESIGNS = ["experimental", "observational", "computational", "replication", "review"];
const KINDS = ["dataset", "file", "figure", "table", "text", "image"];
const PIN_LINKS = ["follows", "instrument", "used", "derivedFrom", "observationBase"];

type Node = Record<string, unknown>;

const list = (value: unknown): unknown[] => (value === undefined || value === null ? [] : Array.isArray(value) ? value : [value]);
const strings = (value: unknown): string[] => list(value).filter((item): item is string => typeof item === "string");
const isDateTime = (value: unknown): value is string => typeof value === "string" && DATE_TIME.test(value) && !Number.isNaN(Date.parse(value));
const isCount = (value: unknown): boolean => typeof value === "number" && Number.isInteger(value) && value >= 0;
const pinsOf = (node: Node, key: string): Node[] => list(node[key]).filter((item): item is Node => typeof item === "object" && item !== null);

/** Every broken rule in a process JSON-LD document, in the document's order. */
export const shapeProblems = (document: JsonObject): ShapeProblem[] => {
  const nodes = list(document["@graph"]).filter((item): item is Node => typeof item === "object" && item !== null);
  const byId = new Map(nodes.map((node) => [String(node.id), node]));
  const typesOf = (node: Node | undefined): string[] => strings(node?.type);
  const is = (id: unknown, type: string): boolean => typeof id === "string" && typesOf(byId.get(id)).includes(type);
  const out: ShapeProblem[] = [];
  const seen = new Set<string>();
  const report = (focus: string, rule: ShapeRule): void => {
    const key = `${focus}\n${rule}`;
    if (seen.has(key) && focus !== "_:") return;
    seen.add(key);
    out.push({ focus, rule, ...SHAPE_RULES[rule] });
  };
  const supported = new Set(nodes.flatMap((node) => strings(node.supports)));

  for (const node of nodes) {
    const id = String(node.id);
    const types = typesOf(node);
    const fail = (rule: ShapeRule, wrong: boolean): void => {
      if (wrong) report(id, rule);
    };
    const atMostOne = (key: string): boolean => list(node[key]).length <= 1;
    const allAre = (key: string, type: string): boolean => list(node[key]).every((value) => is(value, type));
    const targetsAre = (key: string, type: string): boolean => pinsOf(node, key).every((pin) => list(pin.target).every((target) => is(target, type)));
    const oneOf = (key: string, allowed: string[]): boolean => atMostOne(key) && list(node[key]).every((value) => allowed.includes(value as string));
    const drifted = (key: string, current: string): boolean =>
      pinsOf(node, key).some((pin) =>
        strings(pin.cid).some((pinned) => strings(pin.target).some((target) => strings(byId.get(target)?.[current]).some((now) => now !== pinned))),
      );

    if (types.some((type) => UNITS.has(type))) {
      const titles = list(node.title);
      fail("unit-title", titles.length !== 1 || typeof titles[0] !== "string" || titles[0].length < 1);
      const attributed = list(node.attributedTo);
      fail("unit-attributed", attributed.length < 1 || attributed.some((value) => typeof value !== "string"));
    }

    for (const key of PIN_LINKS) {
      for (const pin of pinsOf(node, key)) {
        const targets = list(pin.target);
        if (targets.length !== 1 || typeof targets[0] !== "string") report("_:", "pin-target");
        const cids = list(pin.cid);
        if (cids.length > 1 || cids.some((cid) => typeof cid !== "string" || !CID.test(cid))) report("_:", "pin-cid");
      }
    }

    if (types.includes("Protocol")) {
      fail("protocol-implementedBy", !allAre("implementedBy", "Code"));
      fail("protocol-versionCid", !atMostOne("versionCid") || strings(node.versionCid).some((cid) => !CID.test(cid)));
    }

    if (types.includes("Study")) {
      fail("study-question", !atMostOne("question") || !allAre("question", "Question"));
      fail("study-protocols", !allAre("protocols", "Protocol"));
      fail("study-design", !oneOf("design", DESIGNS));
      fail("study-sampleSize", !atMostOne("sampleSize") || list(node.sampleSize).some((value) => !isCount(value)));
      fail("study-no-question", list(node.question).length < 1);
      fail("study-no-protocol", list(node.protocols).length < 1);
    }

    if (types.includes("Run")) {
      fail("run-partOf", !atMostOne("partOf") || !allAre("partOf", "Study"));
      fail("run-follows", !atMostOne("follows"));
      fail("run-follows-target", !targetsAre("follows", "Protocol"));
      fail("run-instrument-target", !targetsAre("instrument", "Code"));
      fail("run-status", !oneOf("status", STATUSES));
      fail("run-started", !atMostOne("startedAt") || list(node.startedAt).some((value) => !isDateTime(value)));
      fail("run-ended", !atMostOne("endedAt") || list(node.endedAt).some((value) => !isDateTime(value)));
      const started = list(node.startedAt).filter(isDateTime);
      const ended = list(node.endedAt).filter(isDateTime);
      fail("run-time-order", started.some((start) => ended.some((end) => Date.parse(start) > Date.parse(end))));
      fail("run-agents", list(node.agents).some((agent) => typeof agent !== "string" || !AGENT.test(agent)));
      fail("run-condition", !atMostOne("condition") || list(node.condition).some((value) => typeof value !== "string"));
      fail("run-no-study", list(node.partOf).length < 1);
      fail("run-not-plan", ["Protocol", "Study", "Code", "Output"].some((type) => types.includes(type)));
      fail("run-no-method", list(node.follows).length < 1 && list(node.instrument).length < 1);
      for (const pin of pinsOf(node, "instrument")) if (list(pin.cid).length < 1) report("_:", "run-code-unpinned");
      fail("run-code-drift", drifted("instrument", "sourceCid"));
      fail("run-protocol-drift", drifted("follows", "versionCid"));
      const listed = strings(node.partOf).flatMap((study) => strings(byId.get(study)?.conditions));
      fail("run-condition-unknown", listed.length > 0 && strings(node.condition).some((condition) => !listed.includes(condition)));
    }

    if (types.includes("Code")) {
      const cids = list(node.sourceCid);
      fail("code-sourceCid", cids.length !== 1 || typeof cids[0] !== "string" || !CID.test(cids[0]));
    }

    if (types.includes("Output")) {
      const cids = list(node.cid);
      fail("output-cid", cids.length !== 1 || typeof cids[0] !== "string" || !CID.test(cids[0]));
      fail("output-generatedBy", list(node.generatedBy).length !== 1 || !allAre("generatedBy", "Run"));
      fail("output-byteSize", !atMostOne("byteSize") || list(node.byteSize).some((value) => !isCount(value)));
      fail("output-kind", !oneOf("outputKind", KINDS));
      fail("output-derivedFrom-target", !targetsAre("derivedFrom", "Output"));
    }

    if (types.includes("Evidence")) {
      fail("evidence-isGroundedIn", !atMostOne("isGroundedIn") || !allAre("isGroundedIn", "Run"));
      fail("evidence-sourceDocument", !atMostOne("sourceDocument") || !allAre("sourceDocument", "Source"));
      fail("evidence-observationBase-target", !targetsAre("observationBase", "Output"));
      fail("evidence-informs", !allAre("informs", "Question"));
      fail("evidence-ungrounded", list(node.observationBase).length < 1 && list(node.isGroundedIn).length < 1 && list(node.sourceDocument).length < 1);
      for (const pin of pinsOf(node, "observationBase")) if (list(pin.cid).length < 1) report("_:", "evidence-output-unpinned");
      fail("evidence-output-drift", drifted("observationBase", "cid"));
    }

    if (types.includes("Claim")) {
      fail("claim-addresses", !allAre("addresses", "Question"));
      fail("claim-unsupported", !supported.has(id));
    }

    const argued = [...list(node.supports), ...list(node.opposes)];
    if (argued.length > 0) fail("argument-subject", !types.includes("Evidence") && !types.includes("Claim"));
    for (const target of argued) if (!is(target, "Claim")) report(String(target), "argument-object");
    if (list(node.addresses).length > 0) fail("addresses-subject", !types.includes("Claim"));

    if (types.includes("Source")) fail("source-describesActivity", !allAre("describesActivity", "Run"));
  }
  return out;
};

/** The problems for one unit, worst first. Pins report under the unit that holds them. */
export const problemsFor = (problems: ShapeProblem[], focus: string): ShapeProblem[] => {
  const rank: Record<Severity, number> = { Violation: 0, Warning: 1, Info: 2 };
  return problems.filter((problem) => problem.focus === focus).sort((a, b) => rank[a.severity] - rank[b.severity]);
};
