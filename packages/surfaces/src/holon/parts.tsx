type Tab = "parts" | "gaps" | "crossings" | "privacy" | "stance" | "history";

/** Gaps, what crosses in and out, the privacy line, whose records count, history. */
export const Boundary = ({
  view,
  onPick,
  onLight,
  onOpen,
  parts,
}: {
  view: HolonView;
  onPick: (unit: string) => void;
  onLight: (units: string[]) => void;
  onOpen: (ref: HolonRef) => void;
  /** When given, a Parts tab comes first. */
  parts?: ReactNode;
}) => {
  const [tab, setTab] = useState<Tab>(parts ? "parts" : "gaps");
  const { crossings, gaps, privacy, stance } = view.boundary;
  const titleOf = (id: string) => view.names[id] ?? (id === view.ref.id ? { title: view.title, base: view.base } : { title: "A unit outside this graph", base: "none" });
  const tabs: { id: Tab; label: string; count?: number }[] = [
    ...(parts ? [{ id: "parts" as const, label: "Parts", count: view.parts.length }] : []),
    { id: "gaps", label: "Gaps", count: gaps.reduce((n, g) => n + g.units.length, 0) },
    { id: "crossings", label: "In and out", count: crossings.length },
    { id: "privacy", label: "Privacy" },
    { id: "stance", label: "Whose records", count: stance.pending },
    { id: "history", label: "History" },
  ];
  return (
    <div className="hv-boundary-body">
      <div className="hv-tabs" role="tablist">
        {tabs.map((t) => (
          <button key={t.id} type="button" role="tab" aria-selected={tab === t.id} data-dg={`tab-${t.id}`} onClick={() => setTab(t.id)}>
            {t.label}
            {t.count ? <span className="hv-count">{t.count}</span> : null}
          </button>
        ))}
      </div>
      <div className="hv-tabpanel" role="tabpanel">
        {tab === "parts" ? parts : null}
        {tab === "gaps" ? <Gaps gaps={gaps} onLight={onLight} onPick={onPick} titleOf={titleOf} /> : null}
        {tab === "crossings" ? <Crossings crossings={crossings} onPick={onPick} onOpen={onOpen} /> : null}
        {tab === "privacy" ? (
          <section>
            <div className="hv-privacy">
              {(["private", "lab", "published"] as const).map((level) => (
                <div key={level} data-level={level}>
                  <strong>{privacy.counts[level]}</strong>
                  <span>{level === "private" ? "Private" : level === "lab" ? "Shared with the lab" : "Published"}</span>
                </div>
              ))}
            </div>
            <p>{privacy.next}</p>
            <p className="hv-muted">Publishing is a release of a canvas, and writing it to a PDS is always a separate step someone takes on purpose.</p>
          </section>
        ) : null}
        {tab === "stance" ? (
          <section>
            <p>{STANCES.find((s) => s.value === stance.stance)?.hint}.</p>
            <p>
              {counted(stance.active, "argument")} count here. {stance.pending ? `${counted(stance.pending, "more")} would count under a wider stance${stance.pendingBy.length ? `, from ${stance.pendingBy.join(", ")}` : ""}.` : "Nothing is waiting."}
            </p>
          </section>
        ) : null}
        {tab === "history" ? <History events={view.history} onPick={onPick} /> : null}
      </div>
    </div>
  );
};

const Gaps = ({ gaps, onLight, onPick, titleOf }: { gaps: Gap[]; onLight: (u: string[]) => void; onPick: (u: string) => void; titleOf: (id: string) => { title: string; base: string } }) => {
  if (!gaps.length) return <p className="hv-muted">No gaps against the rules at this level.</p>;
  return (
    <ul className="hv-gaps">
      {gaps.map((gap) => (
        <li key={gap.rule} data-severity={gap.severity}>
          <button type="button" className="hv-gap" onClick={() => onLight(gap.units)} title="Light these on the canvas" data-dg={`gap-${gap.rule}`}>
            <span className="hv-count">{gap.units.length}</span>
            <span>{gap.message}</span>
          </button>
          <ul>
            {gap.units.slice(0, 6).map((id) => {
              const unit = titleOf(id);
              return <li key={id}><UnitButton id={id} title={unit.title} base={unit.base} onPick={onPick} /></li>;
            })}
            {gap.units.length > 6 ? <li className="hv-muted">and {gap.units.length - 6} more</li> : null}
          </ul>
        </li>
      ))}
    </ul>
  );
};

const Crossings = ({ crossings, onPick, onOpen }: { crossings: Crossing[]; onPick: (u: string) => void; onOpen: (r: HolonRef) => void }) => {
  if (!crossings.length) return <p className="hv-muted">Nothing crosses this holon's boundary.</p>;
  return (
    <>
      {(["in", "out"] as const).map((direction) => {
        const list = crossings.filter((c) => c.direction === direction);
        if (!list.length) return null;
        return (
          <section key={direction}>
            <h3>{direction === "in" ? "Comes in" : "Goes out"}</h3>
            <ul className="hv-list">
              {list.map((c, i) => (
                <li key={`${c.id}-${i}`}>
                  <UnitButton id={c.id} title={c.title} base={c.base} onPick={onPick} />
                  <div className="hv-why">
                    {c.why}
                    {c.other ? <button type="button" className="hv-link" onClick={() => onOpen(c.other!.ref)}>Open</button> : null}
                  </div>
                </li>
              ))}
            </ul>
          </section>
        );
      })}
    </>
  );
};

export const History = ({ events, onPick }: { events: HolonEvent[]; onPick?: (u: string) => void }) =>
  events.length ? (
    <ol className="hv-history">
      {events.map((e, i) => (
        <li key={`${e.at}-${i}`}>
          <time dateTime={e.at}>{when(e.at)}</time>
          {e.unit && onPick ? <button type="button" className="hv-link" onClick={() => onPick(e.unit!)}>{e.what}</button> : <span>{e.what}</span>}
          <span className="hv-muted">{e.by}</span>
        </li>
      ))}
    </ol>
  ) : (
    <p className="hv-muted">No history yet.</p>
  );

/** A small drawing of a canvas, for history and releases. */
export const Preview = ({ canvas }: { canvas: HolonCanvas }) => {
  if (!canvas.cards.length) return <p className="hv-muted">Nothing on the canvas yet.</p>;
  const width = Math.max(...canvas.cards.map((c) => c.x + c.width)) + 20;
  const height = Math.max(...canvas.cards.map((c) => c.y + c.height)) + 20;
  const byId = new Map(canvas.cards.map((c) => [c.id, c]));
  return (
    <svg className="hv-preview" viewBox={`-10 -10 ${width} ${height}`} role="img" aria-label={`${canvas.cards.length} cards`}>
      {canvas.links.map((l) => {
        const a = byId.get(l.from);
        const b = byId.get(l.to);
        return a && b ? <line key={l.id} x1={a.x + a.width} y1={a.y + a.height / 2} x2={b.x} y2={b.y + b.height / 2} /> : null;
      })}
      {canvas.cards.map((c) => <rect key={c.id} x={c.x} y={c.y} width={c.width} height={c.height} rx={6} />)}
    </svg>
  );
};

export const Composition = ({ units }: { units: Record<string, number> }) => {
  const total = Object.values(units).reduce((a, b) => a + b, 0);
  if (!total) return null;
  const order = ["question", "claim", "evidence", "output", "run", "protocol", "study", "code", "source", "none"];
  return (
    <span className="hv-comp" role="img" aria-label={order.filter((b) => units[b]).map((b) => `${units[b]} ${b}`).join(", ")}>
      {order.filter((b) => units[b]).map((b) => <span key={b} data-base={b} style={{ flexGrow: units[b] }} title={`${units[b]} ${b}`} />)}
    </span>
  );
};

export const DiffView = ({ diff }: { diff: CanvasDiff }) => {
  const rows: [string, { unit: string; title: string }[]][] = [
    ["Added", diff.added],
    ["Removed", diff.removed],
    ["Changed", diff.changed],
    ["Moved", diff.moved],
  ];
  const empty = rows.every(([, list]) => !list.length);
  return (
    <div className="hv-diff" data-dg="diff-result">
      <p className="hv-muted">From {diff.from} to {diff.to}</p>
      {empty ? <p>No differences.</p> : rows.map(([label, list]) => (list.length ? (
        <section key={label}>
          <h4>{label} ({list.length})</h4>
          <ul>{list.map((u) => <li key={u.unit}>{plain(u.title)}</li>)}</ul>
        </section>
      ) : null))}
    </div>
  );
};
