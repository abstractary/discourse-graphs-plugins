// Copies the route table and the wire shapes to the places that cannot import them.
//   node scripts/gen-routes.mjs           writes server/src/routes.gen.ts, server/src/wire.gen.ts and the table in docs/services.md
//   node scripts/gen-routes.mjs --check   writes nothing, and fails when any of them is out of date
//
// The table lives in packages/contract/src/routes.ts, and what each route takes and answers
// with lives beside it in wire.ts. The server stands alone and imports nothing from packages/,
// so it gets a copy of both. The doc gets its table between two markers, and nothing outside
// them is touched.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { ROUTES } from "../packages/contract/src/routes.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = "packages/contract/src/routes.ts";
const WIRE_SOURCE = "packages/contract/src/wire.ts";
const SERVER_FILE = "server/src/routes.gen.ts";
const WIRE_FILE = "server/src/wire.gen.ts";
const DOC_FILE = "docs/services.md";
const BEGIN = "<!-- routes:begin (generated by scripts/gen-routes.mjs from packages/contract/src/routes.ts; run `npm run gen:routes`) -->";
const END = "<!-- routes:end -->";

const quoted = (text) => `'${text.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;

const serverText = () => {
  const lines = Object.entries(ROUTES).map(
    ([name, { method, path, group, client, description }]) =>
      `  ${name}: { method: ${quoted(method)}, path: ${quoted(path)}, group: ${quoted(group)}, client: ${client}, description: ${quoted(description)} },`,
  );
  return [
    `// GENERATED FILE. Do not edit it by hand.`,
    `// It is a copy of the route table in ${SOURCE}, written by scripts/gen-routes.mjs.`,
    `// Change the table there, then run \`npm run gen:routes\`. \`npm run check:routes\` fails when this copy is behind.`,
    `// The server keeps a copy because it stands alone and imports nothing from packages/.`,
    ``,
    `export const ROUTES = {`,
    ...lines,
    `} as const;`,
    ``,
    `export type RouteName = keyof typeof ROUTES;`,
    ``,
  ].join("\n");
};

// The server's copy of the shapes is the file itself, under a heading. That only works while
// the file imports nothing, so an import in it stops the run.
const wireText = (source) => {
  if (/^\s*(import|export)\b[^\n]*\bfrom\b/m.test(source)) {
    throw new Error(`${WIRE_SOURCE} imports from another file. The server gets a plain copy of it, so write every type it needs in the file itself.`);
  }
  return [
    `// GENERATED FILE. Do not edit it by hand.`,
    `// It is a copy of ${WIRE_SOURCE}, written by scripts/gen-routes.mjs.`,
    `// Change the shapes there, then run \`npm run gen:routes\`. \`npm run check:routes\` fails when this copy is behind.`,
    `// The server keeps a copy because it stands alone and imports nothing from packages/.`,
    ``,
    source,
  ].join("\n");
};

// The names of each route's shapes, read from the lines of the `Wire` type.
const shapeNames = (source) => {
  const start = source.indexOf("export type Wire = {");
  const end = source.indexOf("\n};", start);
  if (start < 0 || end < 0) throw new Error(`${WIRE_SOURCE} has no \`export type Wire = { ... };\`.`);
  const shapes = {};
  for (const line of source.slice(start, end).split("\n").slice(1)) {
    if (!line.trim()) continue;
    const found = /^  (\w+): \{(.*)\};$/.exec(line);
    if (!found) throw new Error(`${WIRE_SOURCE}: this line of Wire is not one route on one line:\n${line}`);
    const parts = Object.fromEntries(
      found[2].split(";").map((part) => part.trim()).filter(Boolean).map((part) => part.split(":").map((side) => side.trim())),
    );
    const odd = Object.keys(parts).filter((key) => !["request", "response", "stream"].includes(key));
    if (odd.length > 0) throw new Error(`${WIRE_SOURCE}: Wire.${found[1]} has "${odd[0]}". A route has only request, response and stream.`);
    shapes[found[1]] = parts;
  }
  const missing = Object.keys(ROUTES).filter((name) => !(name in shapes));
  const extra = Object.keys(shapes).filter((name) => !(name in ROUTES));
  if (missing.length > 0) throw new Error(`${WIRE_SOURCE}: Wire has no line for ${missing.join(", ")}. Add one for every route.`);
  if (extra.length > 0) throw new Error(`${WIRE_SOURCE}: Wire has a line for ${extra.join(", ")}, which the route table does not have.`);
  return shapes;
};

const cell = (text) => text.replace(/\|/g, "\\|");
const named = (shape) => (shape ? `\`${cell(shape)}\`` : "");

const docTable = (shapes) =>
  [
    `| Method | Path | Name | Section | What it does | Takes | Answers |`,
    `|---|---|---|---|---|---|---|`,
    ...Object.entries(ROUTES).map(
      ([name, { method, path, group, client, description }]) =>
        `| ${method} | \`${cell(path)}\` | \`${name}\`${client ? "" : " †"} | ${group} | ${cell(description)} | ${named(shapes[name].request)} | ${
          shapes[name].stream ? `lines of ${named(shapes[name].stream)}` : named(shapes[name].response)
        } |`,
    ),
    ``,
    `† The plugins' client never builds this address. The server answers it for other callers, or the caller finds the address in a \`Link\` header.`,
    ``,
    `Takes and Answers name the types in [${WIRE_SOURCE}](../${WIRE_SOURCE}): the JSON body a route takes, and the JSON it answers with. An empty cell is no body, or an answer that is a file, a page or a stored notification.`,
  ].join("\n");

const docText = (current, shapes) => {
  const begin = current.indexOf(BEGIN);
  const end = current.indexOf(END);
  if (begin < 0 || end < begin) {
    throw new Error(`${DOC_FILE} has no route table markers. Put these two lines where the table goes:\n${BEGIN}\n${END}`);
  }
  return `${current.slice(0, begin + BEGIN.length)}\n${docTable(shapes)}\n${current.slice(end)}`;
};

const read = (file) => {
  try {
    return readFileSync(join(root, file), "utf8");
  } catch {
    return "";
  }
};

const check = process.argv.includes("--check");
const wire = read(WIRE_SOURCE);
const wanted = [
  [SERVER_FILE, serverText()],
  [WIRE_FILE, wireText(wire)],
  [DOC_FILE, docText(read(DOC_FILE), shapeNames(wire))],
];
const stale = wanted.filter(([file, text]) => read(file) !== text);

if (check) {
  if (stale.length > 0) {
    for (const [file] of stale) console.error(`${file} is behind ${SOURCE} or ${WIRE_SOURCE}.`);
    console.error("Run `npm run gen:routes` and commit the result.");
    process.exit(1);
  }
  console.log(`${Object.keys(ROUTES).length} routes. ${SERVER_FILE}, ${WIRE_FILE} and ${DOC_FILE} match ${SOURCE} and ${WIRE_SOURCE}.`);
} else {
  for (const [file, text] of stale) writeFileSync(join(root, file), text);
  console.log(`${Object.keys(ROUTES).length} routes. ${stale.length > 0 ? `Wrote ${stale.map(([file]) => file).join(", ")}.` : "Nothing to write."}`);
}
